const BY_ID = new Map(CAUSALES.map((c) => [c.id, c]));

export function causalPorId(id) {
  const key = String(id || "").trim();
  if (BY_ID.has(key)) return BY_ID.get(key);
  if (key === "161") return BY_ID.get("161-necesidades");
  if (key === "159") return BY_ID.get("159-a");
  if (key === "160") return BY_ID.get("160-7");
  return null;
}

export function articuloDeCausal(id) {
  return causalPorId(id)?.articulo || "161";
}

export function opcionesCausalHtml(selected = "161-necesidades") {
  const groups = [
    { art: "159", label: "Artículo 159" },
    { art: "160", label: "Artículo 160" },
    { art: "161", label: "Artículo 161" },
  ];
  return groups
    .map((g) => {
      const opts = CAUSALES.filter((c) => c.articulo === g.art)
        .map(
          (c) =>
            `<option value="${c.id}"${c.id === selected ? " selected" : ""}>${escOpt(c.label)}</option>`,
        )
        .join("");
      return `<optgroup label="${escOpt(g.label)}">${opts}</optgroup>`;
    })
    .join("");
}

function escOpt(s) {
  return String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}
